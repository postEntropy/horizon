#!/usr/bin/env python3
"""Generate a family-level menu inventory from the checked-in Mekanism ports."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def constants(path: Path, name: str) -> list[str]:
    source = path.read_text()
    match = re.search(rf"pub const {name}:\s*&\[&str\]\s*=\s*&\[(.*?)\];", source, re.S)
    if not match:
        raise SystemExit(f"could not find {name} in {path}")
    return re.findall(r'"([^"\n]+)"', match.group(1))


def family(block: str) -> tuple[str, str]:
    name = block.split(":", 1)[-1]
    for suffix, label in (
        ("_combining_factory", "Factories · combining"),
        ("_compressing_factory", "Factories · compressing"),
        ("_crushing_factory", "Factories · crushing"),
        ("_enriching_factory", "Factories · enriching"),
        ("_infusing_factory", "Factories · infusing"),
        ("_injecting_factory", "Factories · injecting"),
        ("_purifying_factory", "Factories · purifying"),
        ("_sawing_factory", "Factories · sawing"),
        ("_smelting_factory", "Factories · smelting"),
    ):
        if name.endswith(suffix):
            return "Factories", label
    if name.endswith(("_bin", "_personal_chest", "_personal_barrel")):
        return "Storage", "Storage · inventory"
    if name.endswith("_energy_cube") or name.endswith("_induction_cell") or name.endswith("_induction_provider"):
        return "Energy", "Energy storage"
    if name.endswith(("_chemical_tank", "_fluid_tank")):
        return "Tanks", "Fluid / chemical tank"
    if name.endswith(("_universal_cable", "_logistical_transporter", "_mechanical_pipe", "_pressurized_tube", "_thermodynamic_conductor")):
        return "Logistics", "Network configuration"
    if "generator" in name or name.endswith("_solar_generator"):
        return "Generators", "Generator"
    if "fission_reactor" in name or "fusion_reactor" in name or "turbine_" in name:
        return "Multiblocks", "Reactor / turbine"
    if name in {"electric_pump", "fluidic_plenisher"}:
        return "Fluid machines", "Pump / fluid transfer"
    if name in {
        "enrichment_chamber", "energized_smelter", "crusher", "combiner",
        "osmium_compressor", "metallurgic_infuser", "purification_chamber",
        "chemical_injection_chamber", "chemical_washer", "chemical_crystallizer",
        "chemical_dissolution_chamber", "chemical_oxidizer", "chemical_infuser",
        "electrolytic_separator", "precision_sawmill", "pressurized_reaction_chamber",
        "painting_machine", "pigment_extractor", "pigment_mixer", "rotary_condensentrator",
        "isotopic_centrifuge", "solar_neutron_activator", "antiprotonic_nucleosynthesizer",
    }:
        return "Processing", "Processing · " + name.replace("_", " ")
    return "Other", "Machine-specific / inspect"


def rows() -> list[tuple[str, str, str]]:
    result = []
    for mod in ("mekanism", "mekanismgenerators"):
        port = ROOT / "ports" / mod
        path = port / "src" / "items.rs"
        blocks = constants(path, "BLOCKS")
        source = (port / "src" / "lib.rs").read_text()
        if mod == "mekanism":
            machine_source = source[source.find("fn is_machine"):source.find("fn screen_id")]
            exact_source = machine_source.split("|| matches!(", 1)[-1]
            exact = set(re.findall(r'"([a-z0-9_]+)"', exact_source))
            suffix_source = machine_source.split("[", 1)[1].split("]", 1)[0]
            suffixes = set(re.findall(r'"(_[a-z0-9_]+)"', suffix_source))
            selected = [b for b in blocks if b.split(":", 1)[-1] in exact or b.split(":", 1)[-1].endswith(tuple(suffixes))]
        else:
            generator_match = re.search(r"fn is_generator\(block: &str\).*?matches!\(\s*block,([\s\S]*?)\n\s*\)\s*\}", source)
            generators = set(re.findall(r'"([a-z0-9_]+:[a-z0-9_]+)"', generator_match.group(1))) if generator_match else set()
            selected = [b for b in blocks if b in generators]
            selected.extend((
                "mekanismgenerators:turbine_valve",
                "mekanismgenerators:fission_reactor_port",
                "mekanismgenerators:fusion_reactor_controller",
                "mekanismgenerators:fusion_reactor_port",
            ))
        for block in sorted(set(selected)):
            group, layout = family(block)
            result.append((mod, group, f"{block} — {layout}"))
    return sorted(result, key=lambda row: (row[0], row[1], row[2]))


def render() -> str:
    data = rows()
    lines = [
        "# Mekanism menu inventory (generated)",
        "",
        "Generated by `python3 tools/mekanism_menu_matrix.py`. It reads the registered block lists and applies the machine-selection rules in each port. Family labels are name-based starting points for batch layout work, not claims of visual parity.",
        "",
        f"Registered machine blocks: **{len(data)}**.",
        "",
        "| Port | Family | Registered block / proposed shared layout | Status |",
        "|---|---|---|---|",
    ]
    for mod, group, description in data:
        lines.append(f"| `{mod}` | {group} | `{description.split(' — ')[0]}` — {description.split(' — ', 1)[1]} | Layout needs visual review |")
    lines.extend([
        "",
        "## Batch plan",
        "",
        "1. Implement one reusable background and widget arrangement per family.",
        "2. Map tier variants and machines with the same slot topology to that family.",
        "3. Keep machine-specific screens in their own layout group when their controls or slot topology differ.",
        "4. Review one representative per family, then spot-check the generated members.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write markdown to this path (stdout by default)")
    args = parser.parse_args()
    content = render()
    if args.output:
        args.output.write_text(content)
    else:
        print(content, end="")


if __name__ == "__main__":
    main()
